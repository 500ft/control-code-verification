function make_observational_tables(root, outDir)
%MAKE_OBSERVATIONAL_TABLES Write the observational result tables as LaTeX.
%   Inputs: evidence/observational/pilot-summary.json,
%   evidence/observational/campaign-summary.json and
%   campaign/observational-design.json (class order). Outputs three booktabs
%   and siunitx tabular fragments in outDir. Every number is read from the
%   JSON files; the same values appear in evidence/observational/table.md.

d = fullfile(root, 'evidence', 'observational');
P = jsondecode(fileread(fullfile(d, 'pilot-summary.json')));
txt = fileread(fullfile(d, 'campaign-summary.json'));
C = jsondecode(txt);
design = jsondecode(fileread(fullfile(root, 'campaign', 'observational-design.json')));
head = "% Generated by figures/matlab/make_observational_tables.m from the observational summary JSON files; do not edit by hand.";
pre = "\sisetup{group-minimum-digits=4}";

% 1. Stage summary
rows = strings(0, 1);
stages = {P, 'Directed + random pilot'; C, 'Randomized development'};
for i = 1:2
    s = stages{i, 1};
    rows(end + 1, 1) = sprintf('%s & %d & %d & %d & %d & %d & %d & %.3f & %.2f \\\\', stages{i, 2}, ...
        s.completed_traces, count(s.trace_classes, 'branch_requirement'), ...
        s.exact_stateful_steps, count(s.step_classes, 'signed_zero_common'), ...
        count(s.step_classes, 'branch_requirement'), count(s.step_classes, 'numeric_bound'), ...
        s.elapsed_s, s.peak_rss_bytes / 2^20); %#ok<AGROW>
end
L = [head; pre
"\begin{tabular}{@{}l S[table-format=4.0] S[table-format=4.0] S[table-format=7.0] S[table-format=1.0] S[table-format=4.0] S[table-format=1.0] S[table-format=3.3] S[table-format=3.2]@{}}"
"\toprule"
" & \multicolumn{2}{c}{Traces} & \multicolumn{4}{c}{Steps} & \multicolumn{2}{c}{Run} \\"
"\cmidrule(lr){2-3}\cmidrule(lr){4-7}\cmidrule(l){8-9}"
"Stage & " + stack("Completed", "") + " & " + stack("Branch-", "affected") + " & " + ...
    stack("Exact-", "covered") + " & " + stack("Signed-zero", "difference") + " & " + ...
    stack("Branch", "difference") + " & " + stack("Bound", "violation") + " & " + ...
    stack("Runtime", "(\unit{\second})") + " & " + stack("Peak RSS", "(\unit{\mebi\byte})") + " \\"
"\midrule"
rows
"\bottomrule"
"\end{tabular}"];
writelines(L, fullfile(outDir, 'observational-stages.tex'));

% 2. Randomized development by variant and stratum
i0 = strfind(txt, '"per_stratum"');
i1 = strfind(txt, '"max_local_error_rad_s"');
keys = regexp(txt(i0:i1), '"((?:zero_reset|tracking_reset)/[a-z_]+)"\s*:\s*\{', 'tokens');
keys = string(cellfun(@(c) c{1}, keys, 'UniformOutput', false));
fields = string(fieldnames(C.per_stratum));
assert(numel(keys) == numel(fields) && all(matlab.lang.makeValidName(keys) == fields(:)'), ...
    'per_stratum keys do not match');
rows = strings(0, 1); last = "";
for i = 1:numel(keys)
    parts = split(keys(i), '/');
    g = C.per_stratum.(fields(i));
    if parts(1) ~= last && last ~= ""
        rows(end + 1, 1) = "\midrule"; %#ok<AGROW>
    end
    shown = ""; if parts(1) ~= last, shown = tt(parts(1)); end
    last = parts(1);
    rows(end + 1, 1) = sprintf('%s & %s & %d & %d & %d & %d \\\\', shown, tt(parts(2)), ...
        g.traces, g.steps, count(g.step_classes, 'branch_requirement'), ...
        count(g.trace_classes, 'branch_requirement')); %#ok<AGROW>
end
L = [head; pre
"\begin{tabular}{@{}ll S[table-format=3.0] S[table-format=6.0] S[table-format=4.0] S[table-format=3.0]@{}}"
"\toprule"
"Variant & Stratum & {Traces} & {Steps} & " + stack("Branch-difference", "steps") + " & " + stack("Branch-affected", "traces") + " \\"
"\midrule"
rows
"\bottomrule"
"\end{tabular}"];
writelines(L, fullfile(outDir, 'observational-strata.tex'));

% 3. Discrepancy classes, in the registered order
classes = string(design.classifications);
rows = strings(numel(classes), 1);
for i = 1:numel(classes)
    c = char(classes(i));
    rows(i) = sprintf('%s & %d & %d & %d & %d \\\\', tt(classes(i)), ...
        count(P.step_classes, c), count(P.trace_classes, c), ...
        count(C.step_classes, c), count(C.trace_classes, c));
end
L = [head; pre
"\begin{tabular}{@{}l S[table-format=2.0] S[table-format=1.0] S[table-format=4.0] S[table-format=4.0]@{}}"
"\toprule"
" & \multicolumn{2}{c}{Pilot} & \multicolumn{2}{c}{Randomized} \\"
"\cmidrule(lr){2-3}\cmidrule(l){4-5}"
"Discrepancy class & {Steps} & {Traces} & {Steps} & {Traces} \\"
"\midrule"
rows
"\bottomrule"
"\end{tabular}"];
writelines(L, fullfile(outDir, 'observational-classes.tex'));
end

function n = count(s, key)
% Classes absent from a summary were counted zero times.
if isstruct(s) && isfield(s, key), n = s.(key); else, n = 0; end
end

function out = stack(a, b)
if b == "", out = "{" + a + "}"; return; end
out = "{\begin{tabular}[b]{@{}c@{}}" + a + "\\" + b + "\end{tabular}}";
end

function out = tt(name)
out = "\texttt{" + strrep(string(name), "_", "\_") + "}";
end
