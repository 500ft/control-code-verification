"""Accessible view derived from the retained observational result JSON files."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
out=ROOT/'evidence/observational'
lines=['<!-- Generated by campaign/render_summary.py; numerical sources linked below. -->',
       '# Observational results', '',
       'Sources: [pilot](pilot-summary.json), [randomized scale](campaign-summary.json),',
       '[independent recount and examples](independent-review.json), [cross-compiler](cross-summary.json).', '',
       '| Stage | Completed traces | Exact-covered steps | Signed-zero difference steps | Exact/rounded branch-difference steps | Branch-affected traces | Bound violations | Runtime (s) | Peak RSS (MiB) |',
       '| :--- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |']
for name,label in [('pilot','Directed + random pilot'),('campaign','Randomized development')]:
    s=json.loads((out/f'{name}-summary.json').read_text())
    lines.append(f"| {label} | {s['completed_traces']:,} | {s['exact_stateful_steps']:,} | {s['step_classes'].get('signed_zero_common',0):,} | {s['step_classes'].get('branch_requirement',0):,} | {s['trace_classes'].get('branch_requirement',0):,} | {s['step_classes'].get('numeric_bound',0):,} | {s['elapsed_s']:.3f} | {s['peak_rss_bytes']/2**20:.2f} |")
lines+=['', 'Signed-zero counts compare C and binary32 on a common prior state. Independent',
        'rollouts give the same counts here. Both stages completed every admitted trace;',
        'no invalid or unclassified trace was omitted. Steps within a trace are dependent.', '',
        '| Variant / stratum | Traces | Steps | Branch-difference steps | Branch-affected traces |',
        '| :--- | ---: | ---: | ---: | ---: |']
s=json.loads((out/'campaign-summary.json').read_text())
for key,g in s['per_stratum'].items():
    lines.append(f"| {key} | {g['traces']:,} | {g['steps']:,} | {g['step_classes'].get('branch_requirement',0):,} | {g['trace_classes'].get('branch_requirement',0):,} |")
lines+=['', '| Discrepancy class | Pilot steps | Pilot traces | Randomized steps | Randomized traces |',
        '| :--- | ---: | ---: | ---: | ---: |']
a=json.loads((out/'pilot-summary.json').read_text());b=json.loads((out/'campaign-summary.json').read_text())
for category in json.loads((ROOT/'campaign/observational-design.json').read_text())['classifications']:
    lines.append(f"| {category} | {a['step_classes'].get(category,0):,} | {a['trace_classes'].get(category,0):,} | {b['step_classes'].get(category,0):,} | {b['trace_classes'].get(category,0):,} |")
(out/'table.md').write_text('\n'.join(lines)+'\n')
